def _progress(enabled: bool, message: str) -> None:
    if enabled:
        print(message, file=sys.stderr, flush=True)


@dataclass
class LammpsDumpFrame:
    frame_index: int
    timestep: int
    positions_nm: list[Vector]
    box_nm: Vector
    forces_ev_ang: list[Vector] | None


@dataclass
class ActiveLearningSample:
    sample_id: int
    cluster_size: int
    frame_index: int
    timestep: int
    molecule_resids: list[int]
    score: float
    max_force_ev_ang: float
    rms_force_ev_ang: float
    min_interatomic_distance_ang: float
    avg_pair_com_distance_ang: float
    avg_contact_count: float
    close_contact_alert: bool
    xyz_path: str | None = None


@dataclass
class _ActiveCandidate:
    frame: LammpsDumpFrame
    mol_indices: tuple[int, ...]
    score: float
    max_force_ev_ang: float
    rms_force_ev_ang: float
    min_interatomic_distance_nm: float
    avg_pair_com_distance_nm: float
    avg_contact_count: float
    close_contact_alert: bool
    compact_score: float
    feature: tuple[float, ...]


def sample_active_learning_clusters(
    dump_path: str | Path,
    reference_gro: str | Path,
    cluster_size: int = 2,
    n_samples: int = 20,
    output_dir: str | Path = "active_learning_samples",
    frame_stride: int = 1,
    max_frames: int | None = None,
    random_frame_samples: int | None = None,
    candidate_seeds_per_frame: int | None = None,
    neighbor_pool: int = 8,
    contact_cutoff_angstrom: float = 5.0,
    close_contact_alert_angstrom: float = 1.2,
    hard_reject_distance_angstrom: float = 0.55,
    random_seed: int = 17,
    write_xyz: bool = True,
    progress: bool = False,
    sampling_mode: str = "film",
    solute_resnames: Sequence[str] = (),
    solvent_resnames: Sequence[str] = (),
    solution_solute_weights: dict[int, float] | None = None,
) -> list[ActiveLearningSample]:
    """Sample MD snapshots that are useful candidates for active learning.

    The sampler reads a LAMMPS custom dump generated by the SevenNet MD input
    and extracts molecular clusters for later DFT labeling. In the absence of
    ensemble/model-deviation uncertainty, it uses practical surrogate signals:
    high force magnitudes, unusually close inter-molecular heavy-atom contacts,
    compact contact-rich clusters, and diversity across frames/geometries.
    """

    if cluster_size < 2:
        raise ValueError("cluster_size must be at least 2")
    if n_samples < 1:
        raise ValueError("n_samples must be at least 1")
    if frame_stride < 1:
        raise ValueError("frame_stride must be at least 1")
    if random_frame_samples is not None and random_frame_samples < 1:
        raise ValueError("random_frame_samples must be at least 1")
    if candidate_seeds_per_frame is not None and candidate_seeds_per_frame < 1:
        raise ValueError("candidate_seeds_per_frame must be at least 1")
    if hard_reject_distance_angstrom < 0.0:
        raise ValueError("hard_reject_distance_angstrom must be non-negative")

    atoms, molecules, _ = read_gro(reference_gro)
    validate_sampling(sampling_mode, solute_resnames, solvent_resnames, solution_solute_weights, molecules)
    frames = read_lammps_dump(
        dump_path,
        frame_stride=frame_stride,
        max_frames=max_frames,
        random_frame_samples=random_frame_samples,
        random_seed=random_seed,
        progress=progress,
    )
    if not frames:
        raise RuntimeError(f"No frames were read from {dump_path}")
    _progress(progress, f"[active-learning] loaded {len(frames)} frame(s) for cluster_size={cluster_size}")

    expected_atoms = len(atoms)
    for frame in frames:
        if len(frame.positions_nm) != expected_atoms:
            raise ValueError(
                f"Frame {frame.frame_index} has {len(frame.positions_nm)} atoms, "
                f"but reference GRO has {expected_atoms}"
            )

    rng = random.Random(random_seed)
    candidates: list[_ActiveCandidate] = []
    for frame_number, frame in enumerate(frames, start=1):
        _progress(
            progress,
            "[active-learning] scoring frame {}/{} for {}mol "
            "(dump_frame={}, step={}, candidates_so_far={})".format(
                frame_number,
                len(frames),
                cluster_size,
                frame.frame_index,
                frame.timestep,
                len(candidates),
            ),
        )
        if sampling_mode == "solution":
            geometry_frame = FrameData(frame.frame_index, None, frame.positions_nm, frame.box_nm)
            geometries = _molecule_geometries(geometry_frame, molecules)
            pair_cache = {}
            for indices in solution_candidates(frame, molecules, cluster_size, neighbor_pool,
                    contact_cutoff_angstrom / 10.0, solute_resnames, solution_solute_weights,
                    rng, candidate_seeds_per_frame):
                candidate = _score_active_candidate(frame, geometry_frame, molecules,
                    geometries, indices, contact_cutoff_angstrom / 10.0,
                    close_contact_alert_angstrom / 10.0,
                    hard_reject_distance_angstrom / 10.0, pair_cache)
                if candidate is not None:
                    candidates.append(candidate)
            continue
        frame_candidates = _frame_active_candidates(
            frame=frame,
            molecules=molecules,
            cluster_size=cluster_size,
            neighbor_pool=neighbor_pool,
            candidate_seeds_per_frame=candidate_seeds_per_frame,
            contact_cutoff_nm=contact_cutoff_angstrom / 10.0,
            close_contact_alert_nm=close_contact_alert_angstrom / 10.0,
            hard_reject_distance_nm=hard_reject_distance_angstrom / 10.0,
            rng=rng,
            progress=progress,
        )
        candidates.extend(frame_candidates)
        _progress(
            progress,
            "[active-learning] finished frame {}/{} for {}mol "
            "(added={}, total_candidates={})".format(
                frame_number,
                len(frames),
                cluster_size,
                len(frame_candidates),
                len(candidates),
            ),
        )

    if not candidates and sampling_mode == "film":
        raise RuntimeError(
            "No active-learning candidates were found. Try increasing "
            "neighbor_pool/contact_cutoff_angstrom or lowering the hard reject distance."
        )

    _progress(progress, f"[active-learning] assigning scores to {len(candidates)} candidate(s)")
    if sampling_mode == "film":
        _assign_active_scores(candidates)
    _progress(progress, f"[active-learning] selecting {n_samples} diverse sample(s)")
    selected = (select_solution(candidates, molecules, solute_resnames, cluster_size,
        solution_solute_weights, n_samples, _select_diverse_active_candidates, output_dir,
        score_group=_assign_active_scores) if sampling_mode == "solution"
        else _select_diverse_active_candidates(candidates, n_samples))

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    _progress(progress, f"[active-learning] writing selected samples to {output_dir}")

    samples: list[ActiveLearningSample] = []
    for sample_id, candidate in enumerate(selected, start=1):
        molecule_resids = [molecules[i].resid for i in candidate.mol_indices]
        xyz_path: str | None = None
        if write_xyz:
            xyz_file = output_dir / (
                f"al_cluster_{cluster_size}mol_{sample_id:04d}_"
                f"step{candidate.frame.timestep:08d}_"
                f"res{'-'.join(str(r) for r in molecule_resids)}.xyz"
            )
            write_active_cluster_xyz(
                xyz_file,
                atoms,
                molecules,
                candidate,
            )
            xyz_path = str(xyz_file)

        samples.append(
            ActiveLearningSample(
                sample_id=sample_id,
                cluster_size=cluster_size,
                frame_index=candidate.frame.frame_index,
                timestep=candidate.frame.timestep,
                molecule_resids=molecule_resids,
                score=candidate.score,
                max_force_ev_ang=candidate.max_force_ev_ang,
                rms_force_ev_ang=candidate.rms_force_ev_ang,
                min_interatomic_distance_ang=candidate.min_interatomic_distance_nm * 10.0,
                avg_pair_com_distance_ang=candidate.avg_pair_com_distance_nm * 10.0,
                avg_contact_count=candidate.avg_contact_count,
                close_contact_alert=candidate.close_contact_alert,
                xyz_path=xyz_path,
            )
        )

    _write_active_metadata(output_dir, samples)
    return samples


def sample_active_learning_clusters_for_sizes(
    dump_path: str | Path,
    reference_gro: str | Path,
    cluster_sizes: Sequence[int],
    n_samples: int,
    output_dir: str | Path = "active_learning_samples",
    **kwargs,
) -> dict[int, list[ActiveLearningSample]]:
    """Sample active-learning candidates for multiple cluster sizes."""

    results: dict[int, list[ActiveLearningSample]] = {}
    for cluster_size in cluster_sizes:
        size_output = Path(output_dir) / f"{cluster_size}mol"
        results[cluster_size] = sample_active_learning_clusters(
            dump_path=dump_path,
            reference_gro=reference_gro,
            cluster_size=cluster_size,
            n_samples=n_samples,
            output_dir=size_output,
            **kwargs,
        )
    return results


def read_lammps_dump(
    path: str | Path,
    frame_stride: int = 1,
    max_frames: int | None = None,
    random_frame_samples: int | None = None,
    random_seed: int = 17,
    progress: bool = False,
) -> list[LammpsDumpFrame]:
    """Read an orthogonal LAMMPS custom dump with x/y/z and optional fx/fy/fz."""

    path = Path(path)
    if random_frame_samples is not None:
        return _read_random_lammps_dump_frames(
            path,
            frame_stride=frame_stride,
            max_frames=max_frames,
            random_frame_samples=random_frame_samples,
            random_seed=random_seed,
            progress=progress,
        )

    frames: list[LammpsDumpFrame] = []
    seen_frames = 0

    with path.open("r", encoding="utf-8") as handle:
        while True:
            line = handle.readline()
            if not line:
                break
            if not line.startswith("ITEM: TIMESTEP"):
                continue

            timestep = int(handle.readline().strip())
            _expect_item(handle.readline(), "ITEM: NUMBER OF ATOMS")
            natoms = int(handle.readline().strip())
            box_header = handle.readline().strip()
            _expect_item(box_header, "ITEM: BOX BOUNDS")
            box_bounds = [_parse_box_bound(handle.readline()) for _ in range(3)]
            box_nm = tuple((hi - lo) / 10.0 for lo, hi in box_bounds)

            atom_header = handle.readline().strip()
            _expect_item(atom_header, "ITEM: ATOMS")
            columns = atom_header.split()[2:]

            if seen_frames % frame_stride != 0:
                for _ in range(natoms):
                    handle.readline()
                seen_frames += 1
                continue

            positions: list[Vector | None] = [None] * natoms
            forces: list[Vector | None] | None = (
                [None] * natoms if all(name in columns for name in ("fx", "fy", "fz")) else None
            )

            col = {name: index for index, name in enumerate(columns)}
            coord_mode = _coordinate_mode(columns)
            for _ in range(natoms):
                parts = handle.readline().split()
                atom_id = int(parts[col["id"]]) - 1
                if atom_id < 0 or atom_id >= natoms:
                    raise ValueError(f"Atom id {atom_id + 1} is outside 1..{natoms}")
                positions[atom_id] = _read_position_nm(parts, col, coord_mode, box_bounds)
                if forces is not None:
                    forces[atom_id] = (
                        float(parts[col["fx"]]),
                        float(parts[col["fy"]]),
                        float(parts[col["fz"]]),
                    )

            if any(pos is None for pos in positions):
                raise ValueError(f"Frame at timestep {timestep} has missing atom ids")

            frame_forces: list[Vector] | None = None
            if forces is not None:
                if any(force is None for force in forces):
                    raise ValueError(f"Frame at timestep {timestep} has missing force rows")
                frame_forces = [force for force in forces if force is not None]

            frames.append(
                LammpsDumpFrame(
                    frame_index=seen_frames,
                    timestep=timestep,
                    positions_nm=[pos for pos in positions if pos is not None],
                    box_nm=(box_nm[0], box_nm[1], box_nm[2]),
                    forces_ev_ang=frame_forces,
                )
            )
            if progress and (len(frames) == 1 or len(frames) % 10 == 0):
                _progress(
                    progress,
                    f"[active-learning] read {len(frames)} frame(s) "
                    f"(latest dump_frame={seen_frames}, step={timestep})",
                )
            seen_frames += 1

            if max_frames is not None and len(frames) >= max_frames:
                break

    _progress(progress, f"[active-learning] finished reading {len(frames)} frame(s)")
    return frames


def _read_random_lammps_dump_frames(
    path: Path,
    frame_stride: int,
    max_frames: int | None,
    random_frame_samples: int,
    random_seed: int,
    progress: bool,
) -> list[LammpsDumpFrame]:
    offsets: list[tuple[int, int]] = []
    seen_frames = 0
    eligible_frames = 0
    file_size = max(path.stat().st_size, 1)
    last_report_percent = -5

    _progress(progress, f"[active-learning] scanning dump frame offsets in {path}")
    with path.open("r", encoding="utf-8") as handle:
        while True:
            offset = handle.tell()
            line = handle.readline()
            if not line:
                break
            if not line.startswith("ITEM: TIMESTEP"):
                continue

            handle.readline()
            _expect_item(handle.readline(), "ITEM: NUMBER OF ATOMS")
            natoms = int(handle.readline().strip())
            _expect_item(handle.readline(), "ITEM: BOX BOUNDS")
            for _ in range(3):
                handle.readline()
            _expect_item(handle.readline(), "ITEM: ATOMS")
            for _ in range(natoms):
                handle.readline()

            if seen_frames % frame_stride == 0:
                if max_frames is not None and eligible_frames >= max_frames:
                    break
                offsets.append((seen_frames, offset))
                eligible_frames += 1
            seen_frames += 1
            percent = int(handle.tell() * 100 / file_size)
            if progress and percent >= last_report_percent + 5:
                last_report_percent = percent
                _progress(
                    progress,
                    "[active-learning] scanning dump offsets: {}% "
                    "(seen_frames={}, eligible_frames={})".format(
                        min(percent, 100),
                        seen_frames,
                        eligible_frames,
                    ),
                )

    rng = random.Random(random_seed)
    total_eligible = len(offsets)
    if len(offsets) > random_frame_samples:
        offsets = sorted(rng.sample(offsets, random_frame_samples), key=lambda item: item[0])
    _progress(
        progress,
        "[active-learning] selected {}/{} eligible frame(s) for detailed reading".format(
            len(offsets),
            total_eligible,
        ),
    )

    frames: list[LammpsDumpFrame] = []
    with path.open("r", encoding="utf-8") as handle:
        for selected_number, (frame_index, offset) in enumerate(offsets, start=1):
            _progress(
                progress,
                "[active-learning] reading selected frame {}/{} (dump_frame={})".format(
                    selected_number,
                    len(offsets),
                    frame_index,
                ),
            )
            handle.seek(offset)
            frames.append(_read_lammps_dump_frame_at_current_position(handle, frame_index))

    _progress(progress, f"[active-learning] finished reading {len(frames)} selected frame(s)")
    return frames


