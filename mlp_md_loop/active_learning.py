def write_active_cluster_xyz(
    path: str | Path,
    atoms: Sequence[AtomRecord],
    molecules: Sequence[MoleculeRecord],
    candidate: _ActiveCandidate,
) -> None:
    """Write a selected active-learning cluster as centered XYZ in Angstrom."""

    path = Path(path)
    frame = FrameData(
        frame_index=candidate.frame.frame_index,
        time_ps=None,
        positions_nm=candidate.frame.positions_nm,
        box_nm=candidate.frame.box_nm,
    )
    geometries = _molecule_geometries(frame, molecules)
    seed_center = geometries[candidate.mol_indices[0]].center

    cluster_atoms: list[tuple[str, Vector]] = []
    for mol_index in candidate.mol_indices:
        mol = molecules[mol_index]
        mol_center = geometries[mol_index].center
        delta = minimum_image_delta(seed_center, mol_center, frame.box_nm)
        target_center = add(seed_center, delta)
        shift = sub(target_center, mol_center)
        unwrapped_positions = _unwrapped_molecule_positions(frame, mol, mol.atom_indices)
        for atom_index in mol.atom_indices:
            pos_nm = add(unwrapped_positions[atom_index], shift)
            cluster_atoms.append((atoms[atom_index].element, scale(pos_nm, 10.0)))

    center_ang = mean_vector([pos for _, pos in cluster_atoms])
    centered_atoms = [(element, sub(pos, center_ang)) for element, pos in cluster_atoms]

    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"{len(centered_atoms)}\n")
        handle.write(
            "active_learning score={:.6f} step={} frame={} cluster_size={} residues={} "
            "max_force_ev_ang={:.6f} rms_force_ev_ang={:.6f} min_dist_ang={:.6f}\n".format(
                candidate.score,
                candidate.frame.timestep,
                candidate.frame.frame_index,
                len(candidate.mol_indices),
                ",".join(str(molecules[i].resid) for i in candidate.mol_indices),
                candidate.max_force_ev_ang,
                candidate.rms_force_ev_ang,
                candidate.min_interatomic_distance_nm * 10.0,
            )
        )
        for element, pos in centered_atoms:
            handle.write(f"{element:2s} {pos[0]:14.8f} {pos[1]:14.8f} {pos[2]:14.8f}\n")


def _frame_active_candidates(
    frame: LammpsDumpFrame,
    molecules: Sequence[MoleculeRecord],
    cluster_size: int,
    neighbor_pool: int,
    candidate_seeds_per_frame: int | None,
    contact_cutoff_nm: float,
    close_contact_alert_nm: float,
    hard_reject_distance_nm: float,
    rng: random.Random,
    progress: bool = False,
) -> list[_ActiveCandidate]:
    geometry_frame = FrameData(
        frame_index=frame.frame_index,
        time_ps=None,
        positions_nm=frame.positions_nm,
        box_nm=frame.box_nm,
    )
    geometries = _molecule_geometries(geometry_frame, molecules)
    neighbor_pool = max(cluster_size - 1, neighbor_pool)
    seen: set[tuple[int, ...]] = set()
    rough: list[tuple[float, tuple[int, ...]]] = []
    seed_indices = list(range(len(geometries)))
    if candidate_seeds_per_frame is not None and candidate_seeds_per_frame < len(seed_indices):
        seed_indices = sorted(rng.sample(seed_indices, candidate_seeds_per_frame))

    for seed_number, seed_index in enumerate(seed_indices, start=1):
        if progress and (seed_number == 1 or seed_number % 25 == 0 or seed_number == len(seed_indices)):
            _progress(
                progress,
                "[active-learning]   seed search {}/{} "
                "(frame={}, rough_candidates={})".format(
                    seed_number,
                    len(seed_indices),
                    frame.frame_index,
                    len(rough),
                ),
            )
        seed_geom = geometries[seed_index]
        neighbors: list[tuple[float, int]] = []
        for other_index, other_geom in enumerate(geometries):
            if seed_index == other_index:
                continue
            dist = norm(minimum_image_delta(seed_geom.center, other_geom.center, frame.box_nm))
            neighbors.append((dist, other_index))
        neighbors.sort(key=lambda item: item[0])
        pool = [index for _, index in neighbors[:neighbor_pool]]

        for combo in itertools.combinations(pool, cluster_size - 1):
            mol_indices = tuple(sorted((seed_index, *combo)))
            if mol_indices in seen:
                continue
            seen.add(mol_indices)
            pair_dists = [
                norm(minimum_image_delta(geometries[i].center, geometries[j].center, frame.box_nm))
                for i, j in itertools.combinations(mol_indices, 2)
            ]
            compactness = sum(pair_dists) / len(pair_dists)
            rough.append((compactness + rng.random() * 1e-9, mol_indices))

    max_rough = max(6000, 700 * cluster_size)
    rough.sort(key=lambda item: item[0])
    pair_cache: dict[tuple[int, int], dict[str, float]] = {}
    candidates: list[_ActiveCandidate] = []
    rough_to_score = rough[:max_rough]
    _progress(
        progress,
        "[active-learning]   scoring {} rough candidate(s) for frame {}".format(
            len(rough_to_score),
            frame.frame_index,
        ),
    )
    for rough_number, (_, mol_indices) in enumerate(rough_to_score, start=1):
        candidate = _score_active_candidate(
            frame=frame,
            geometry_frame=geometry_frame,
            molecules=molecules,
            geometries=geometries,
            mol_indices=mol_indices,
            contact_cutoff_nm=contact_cutoff_nm,
            close_contact_alert_nm=close_contact_alert_nm,
            hard_reject_distance_nm=hard_reject_distance_nm,
            pair_cache=pair_cache,
        )
        if candidate is not None:
            candidates.append(candidate)
        if progress and (
            rough_number == 1 or rough_number % 1000 == 0 or rough_number == len(rough_to_score)
        ):
            _progress(
                progress,
                "[active-learning]   contact scoring {}/{} "
                "(frame={}, accepted={})".format(
                    rough_number,
                    len(rough_to_score),
                    frame.frame_index,
                    len(candidates),
                ),
            )

    return candidates


def _score_active_candidate(
    frame: LammpsDumpFrame,
    geometry_frame: FrameData,
    molecules: Sequence[MoleculeRecord],
    geometries: Sequence,
    mol_indices: tuple[int, ...],
    contact_cutoff_nm: float,
    close_contact_alert_nm: float,
    hard_reject_distance_nm: float,
    pair_cache: dict[tuple[int, int], dict[str, float]],
) -> _ActiveCandidate | None:
    pair_metrics = []
    for i, j in itertools.combinations(mol_indices, 2):
        pair_key = (i, j) if i < j else (j, i)
        if pair_key not in pair_cache:
            pair_cache[pair_key] = _pair_active_metrics(
                geometry_frame,
                molecules[i],
                molecules[j],
                geometries[i],
                geometries[j],
                contact_cutoff_nm,
            )
        metrics = pair_cache[pair_key]
        if metrics["min_distance"] < hard_reject_distance_nm:
            return None
        pair_metrics.append(metrics)

    if not _is_contact_connected(mol_indices, pair_metrics, contact_cutoff_nm):
        return None

    cluster_atom_indices = list(
        itertools.chain.from_iterable(molecules[i].atom_indices for i in mol_indices)
    )
    force_mags = _cluster_force_magnitudes(frame.forces_ev_ang, cluster_atom_indices)
    max_force = max(force_mags) if force_mags else 0.0
    rms_force = math.sqrt(sum(value * value for value in force_mags) / len(force_mags)) if force_mags else 0.0

    avg_com = sum(metric["com_distance"] for metric in pair_metrics) / len(pair_metrics)
    min_dist = min(metric["min_distance"] for metric in pair_metrics)
    avg_contacts = sum(metric["contact_count"] for metric in pair_metrics) / len(pair_metrics)
    close_alert = min_dist <= close_contact_alert_nm
    compact_score = 1.0 / (1.0 + avg_com)

    return _ActiveCandidate(
        frame=frame,
        mol_indices=mol_indices,
        score=0.0,
        max_force_ev_ang=max_force,
        rms_force_ev_ang=rms_force,
        min_interatomic_distance_nm=min_dist,
        avg_pair_com_distance_nm=avg_com,
        avg_contact_count=avg_contacts,
        close_contact_alert=close_alert,
        compact_score=compact_score,
        feature=(),
    )


def _pair_active_metrics(
    frame: FrameData,
    mol_a: MoleculeRecord,
    mol_b: MoleculeRecord,
    geom_a,
    geom_b,
    contact_cutoff_nm: float,
) -> dict[str, float]:
    com_distance = norm(minimum_image_delta(geom_a.center, geom_b.center, frame.box_nm))
    min_distance = float("inf")
    contact_count = 0

    for atom_i in mol_a.heavy_atom_indices:
        pos_i = frame.positions_nm[atom_i]
        for atom_j in mol_b.heavy_atom_indices:
            distance = norm(minimum_image_delta(pos_i, frame.positions_nm[atom_j], frame.box_nm))
            if distance < min_distance:
                min_distance = distance
            if distance <= contact_cutoff_nm:
                contact_count += 1

    return {
        "com_distance": com_distance,
        "min_distance": min_distance,
        "contact_count": float(contact_count),
    }


def _assign_active_scores(candidates: Sequence[_ActiveCandidate]) -> None:
    max_force_scale = _robust_high_scale(candidate.max_force_ev_ang for candidate in candidates)
    rms_force_scale = _robust_high_scale(candidate.rms_force_ev_ang for candidate in candidates)
    contact_scale = _robust_high_scale(candidate.avg_contact_count for candidate in candidates)
    max_frame = max(candidate.frame.frame_index for candidate in candidates) or 1

    for candidate in candidates:
        norm_max_force = min(candidate.max_force_ev_ang / max_force_scale, 1.5)
        norm_rms_force = min(candidate.rms_force_ev_ang / rms_force_scale, 1.5)
        norm_contacts = min(candidate.avg_contact_count / contact_scale, 1.5)
        close_score = 1.0 if candidate.close_contact_alert else 0.0

        candidate.score = (
            0.42 * min(norm_max_force, 1.0)
            + 0.24 * min(norm_rms_force, 1.0)
            + 0.18 * min(norm_contacts, 1.0)
            + 0.10 * candidate.compact_score
            + 0.06 * close_score
        )
        candidate.feature = (
            norm_max_force,
            norm_rms_force,
            candidate.min_interatomic_distance_nm * 8.0,
            candidate.avg_pair_com_distance_nm,
            norm_contacts,
            candidate.frame.frame_index / max_frame,
        )


def _select_diverse_active_candidates(
    candidates: Sequence[_ActiveCandidate],
    n_samples: int,
) -> list[_ActiveCandidate]:
    ranked = sorted(candidates, key=lambda candidate: candidate.score, reverse=True)
    selected = [ranked[0]]
    remaining = ranked[1:]

    while remaining and len(selected) < n_samples:
        best_index = 0
        best_value = -float("inf")
        for index, candidate in enumerate(remaining):
            diversity = min(_feature_distance(candidate.feature, item.feature) for item in selected)
            overlap = max(_molecule_overlap(candidate.mol_indices, item.mol_indices) for item in selected)
            value = 0.72 * candidate.score + 0.28 * min(diversity, 1.0) - 0.18 * overlap
            if value > best_value:
                best_value = value
                best_index = index
        selected.append(remaining.pop(best_index))

    return selected


def _is_contact_connected(
    mol_indices: tuple[int, ...],
    pair_metrics: Sequence[dict[str, float]],
    contact_cutoff_nm: float,
) -> bool:
    parent = {index: index for index in mol_indices}

    def find(index: int) -> int:
        while parent[index] != index:
            parent[index] = parent[parent[index]]
            index = parent[index]
        return index

    def union(a: int, b: int) -> None:
        root_a = find(a)
        root_b = find(b)
        if root_a != root_b:
            parent[root_b] = root_a

    for (i, j), metrics in zip(itertools.combinations(mol_indices, 2), pair_metrics):
        if metrics["min_distance"] <= contact_cutoff_nm or metrics["com_distance"] <= 1.20:
            union(i, j)

    return len({find(index) for index in mol_indices}) == 1


def _cluster_force_magnitudes(
    forces_ev_ang: Sequence[Vector] | None,
    atom_indices: Sequence[int],
) -> list[float]:
    if forces_ev_ang is None:
        return []
    return [norm(forces_ev_ang[index]) for index in atom_indices]


def _molecule_overlap(a: Sequence[int], b: Sequence[int]) -> float:
    if not a:
        return 0.0
    return len(set(a) & set(b)) / len(set(a))


def _robust_high_scale(values: Iterable[float]) -> float:
    sorted_values = sorted(float(value) for value in values)
    if not sorted_values:
        return 1.0
    index = min(len(sorted_values) - 1, max(0, int(0.95 * (len(sorted_values) - 1))))
    return max(sorted_values[index], 1e-12)


def _feature_distance(a: Sequence[float], b: Sequence[float]) -> float:
    length = min(len(a), len(b))
    if length == 0:
        return 0.0
    return math.sqrt(sum((a[i] - b[i]) ** 2 for i in range(length)) / length)


def _write_active_metadata(output_dir: Path, samples: Sequence[ActiveLearningSample]) -> None:
    json_path = output_dir / "active_learning_samples.json"
    csv_path = output_dir / "active_learning_samples.csv"

    with json_path.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump([asdict(sample) for sample in samples], handle, indent=2)
        handle.write("\n")

    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(ActiveLearningSample.__dataclass_fields__))
        writer.writeheader()
        for sample in samples:
            row = asdict(sample)
            row["molecule_resids"] = " ".join(str(item) for item in sample.molecule_resids)
            writer.writerow(row)


def _coordinate_mode(columns: Sequence[str]) -> str:
    for mode in ("x", "xu", "xs"):
        names = (mode, mode.replace("x", "y", 1), mode.replace("x", "z", 1))
        if all(name in columns for name in names):
            return mode
    raise ValueError("LAMMPS dump must contain x/y/z, xu/yu/zu, or xs/ys/zs columns")


def _read_position_nm(
    parts: Sequence[str],
    col: dict[str, int],
    coord_mode: str,
    box_bounds: Sequence[tuple[float, float]],
) -> Vector:
    if coord_mode == "x":
        return (
            float(parts[col["x"]]) / 10.0,
            float(parts[col["y"]]) / 10.0,
            float(parts[col["z"]]) / 10.0,
        )
    if coord_mode == "xu":
        return (
            float(parts[col["xu"]]) / 10.0,
            float(parts[col["yu"]]) / 10.0,
            float(parts[col["zu"]]) / 10.0,
        )

    coords = []
    for axis, (lo, hi) in zip(("xs", "ys", "zs"), box_bounds):
        coords.append((lo + float(parts[col[axis]]) * (hi - lo)) / 10.0)
    return (coords[0], coords[1], coords[2])


def _parse_box_bound(line: str) -> tuple[float, float]:
    fields = line.split()
    if len(fields) < 2:
        raise ValueError(f"Invalid BOX BOUNDS line: {line!r}")
    return float(fields[0]), float(fields[1])


def _expect_item(line: str, prefix: str) -> None:
    if not line.startswith(prefix):
        raise ValueError(f"Expected {prefix!r}, got {line.strip()!r}")
